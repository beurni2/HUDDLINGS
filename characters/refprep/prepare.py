"""Prepares a species' references from its master sheets (spec section 5b,
phase 2), every step in order:

    python3 characters/refprep/prepare.py dog

1. crop.py      every panel of the four sheets, into ref/panels/
2. measure.py   the turnaround's silhouettes, landmarks, proportions and outlines
3. palette.py   the swatches and each region's dominant colour, against the printed values
4. markings.py  the proposed marking map, shown on the panels that settle it
5. model.py     model.json, the proposed locked model

The inputs written by hand are in characters/<species>/refmap/; everything in
ref/ and model.json is regenerated byte for byte from them and the sheets. Both
are deleted first, so an output the scripts no longer write disappears, and the
freshness checks (CI, the pre-commit hook) see it go."""
import shutil
import sys

import crop
import markings
import measure
import model
import palette
import sheets

STEPS = (crop, measure, palette, markings, model)


def main(argv):
    if len(argv) != 1:
        print(__doc__)
        return 2
    folder = sheets.ROOT / "characters" / argv[0]
    if not (folder / "refmap").is_dir():
        print(f"prepare: characters/{argv[0]}/refmap does not exist")
        return 2
    shutil.rmtree(folder / "ref", ignore_errors=True)
    (folder / "model.json").unlink(missing_ok=True)
    for step in STEPS:
        code = step.main(argv)
        if code:
            return code
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
